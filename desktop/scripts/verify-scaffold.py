"""Byte comparisons against the existing scaffold implementation, in fixtures."""
from pathlib import Path
import importlib.util
import itertools
import json
import subprocess
import sys
import tempfile

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT))
spec=importlib.util.spec_from_file_location("migration_scaffold_reference",ROOT/"main/core/project_scaffold.py")
reference=importlib.util.module_from_spec(spec)
spec.loader.exec_module(reference)
cases=[dict(name="Demo Sketch",includeH=h,includeCpp=cpp,template=template)
       for template,h,cpp in itertools.product(("standard","bare","blink"),(False,True),(False,True))]
cases += [dict(name=name,includeH=True,includeCpp=True,template="standard")
          for name in (" café/Board ","", "A.B", "Test-2")]
scratch=ROOT/"audit/migration/scratch"
scratch.mkdir(parents=True,exist_ok=True)
with tempfile.TemporaryDirectory(prefix="scaffold-parity-",dir=scratch) as directory:
    fixture=Path(directory)
    expected=[]
    for index,options in enumerate(cases):
        parent=fixture/f"python-case-{index}"
        parent.mkdir()
        project=reference.create_project_scaffold(str(parent),options["name"],include_h=options["includeH"],
                 include_cpp=options["includeCpp"],template_type=options["template"])
        expected.append({p.name:p.read_bytes().decode("utf-8") for p in project.iterdir()})
    executable=ROOT/"desktop/target/debug"/("scaffold_probe.exe" if sys.platform=="win32" else "scaffold_probe")
    result=subprocess.run([str(executable),str(ROOT),str(fixture)],input=json.dumps(cases),text=True,capture_output=True,check=True)
    actual=json.loads(result.stdout)
    assert len(expected)==len(actual)
    for index,(before,after) in enumerate(zip(expected,actual)):
        assert before==after,f"Scaffold parity case {index}: generated bytes differ"
print(json.dumps(dict(reference="main/core/project_scaffold.py",cases=len(cases),passed=True,liveProjectAccess=False)))
